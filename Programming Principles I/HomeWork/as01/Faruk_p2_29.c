#include <stdio.h>

int main(void) {
    // Uppercase letters
    printf("A = %d\n", 'A');
    printf("B = %d\n", 'B');
    printf("C = %d\n", 'C');

    // Lowercase letters
    printf("a = %d\n", 'a');
    printf("b = %d\n", 'b');
    printf("c = %d\n", 'c');

    // Digits
    printf("0 = %d\n", '0');
    printf("1 = %d\n", '1');
    printf("2 = %d\n", '2');

    // Symbols
    printf("$ = %d\n", '$');
    printf("* = %d\n", '*');
    printf("+ = %d\n", '+');
    printf("/ = %d\n", '/');

    // Space
    printf("  = %d (space)\n", ' ');

    return 0;
}
